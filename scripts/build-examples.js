async function run() {
  const outDir = path.resolve("examples");
  fs.mkdirSync(outDir, { recursive: true });

  const index = [];
  for (const brief of BRIEFS) {
    const spec = think(brief);
    const html = renderHTML(spec);
    const htmlPath = path.join(outDir, `${brief.name}.html`);
    const pngPath = path.join(outDir, `${brief.name}.png`);
    fs.writeFileSync(htmlPath, html);
    await htmlToPng(html, { width: spec.format.w, height: spec.format.h, outPath: pngPath });
    console.log(
      `${brief.name.padEnd(22)} -> ${spec.layout.id} / ${spec.palette.id} / ${spec.pairing.id} (${spec.format.id})`
    );
    index.push({ brief, spec: { layout: spec.layout.id, palette: spec.palette.id, pairing: spec.pairing.id, format: spec.format.id } });
  }

  // Write a small markdown gallery so the PNGs render on GitHub.
  const md = [
    "# Example gallery",
    "",
    "Every image below was generated by the Brain from a plain text brief — no manual design.",
    "",
    ...index.map(
      (e) =>
        `### ${e.brief.headline}\n\n` +
        `\`${e.spec.layout}\` · \`${e.spec.palette}\` · \`${e.spec.pairing}\` · \`${e.spec.format}\`\n\n` +
        `<img src="./${e.brief.name}.png" width="360" alt="${e.brief.headline}">\n`
    ),
  ].join("\n");
  fs.writeFileSync(path.join(outDir, "README.md"), md + "\n");
  console.log(`\nGallery written to examples/README.md (${index.length} posts).`);
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
